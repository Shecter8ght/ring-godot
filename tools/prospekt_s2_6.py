def removals(p) -> None:
    for lst in ("walls", "boxes", "slabs"):
        p.remove["pieces"].append({"list": lst, "rect": CONTOUR, "inside": CONTOUR, "ymin": -0.5, "ymax": 13.5})
    for lst in ("stairs", "lamps"):
        p.remove["pieces"].append({"list": lst, "rect": [-142.5, 43.4, -61.5, 88.3]})
    p.remove["nodes"] += ["Ladder_Lift", "Ladder_Hatch"]
    base = p.base()["filler"]["items"]
    r = (-142.4, 47.9, -62.2, 88.0)
    kits = sorted({it[0] for it in base if r[0] <= it[1] <= r[2] and r[1] <= it[2] <= r[3]})
    n = p.drop_items(kits, list(r))
    p.log.append(f"убрано вещей старого корпуса внутри контура: {n} ({len(kits)} видов)")


# =============================================================================================== лестницы
def _mx(x: float, mir: bool) -> float:
    return -204.0 - x if mir else x


def _stepped(p, x: float, z_from: float, z_to: float, y_from: float, n: int = 10, h: float = 1.0, t: float = 0.12, mat: str = "concrete") -> None:
    """Глухое ограждение вдоль марша ступенями: каждая ступень — коробка от низа ступени до +h над ней."""
    tr = (z_to - z_from) / n
    for i in range(n):
        top = y_from + RISE * (i + 1)
        p.box(x, top + (h - RISE) / 2.0, z_from + tr * (i + 0.5), t, h + RISE, abs(tr), mat)


def visitor_stair(p, b: B, mir: bool, tag: str) -> None:
    """Лестница посетителей в вестибюле: марши вдоль Z, четыре марша, входной пол — у южного конца, открыта на восток (запад — у зеркальной)."""
    w0, w1 = -122.0, -118.3                      # запад: стена арендатора и открытая сторона
    zn, zl, zs, zz = 52.8, 54.4, 57.4, 59.0      # север, конец северной площадки, начало южной, юг
    xa, xb = -119.175, -121.125                  # колонка у вестибюля (F1, F3) и у стены (F2, F4)
    X = lambda v: _mx(v, mir)                    # noqa: E731
    lo, hi = sorted((X(w0), X(w1)))
    cx = (lo + hi) / 2.0
    st = p.add["stairs"]
    def flight(x, ya, za, yb, zb, fill):
        rec = {"from": [X(x), ya, za], "to": [X(x), yb, zb], "width": FW, "count": 10, "mat": "concrete", "rails": "both"}
        if fill:
            rec["fill"] = 0.0
        st.append(rec)
    flight(xa, 0.0, zs, 1.5, zl, True)
    flight(xb, 1.5, zl, 3.0, zs, True)
    flight(xa, 3.0, zs, 4.5, zl, False)
    flight(xb, 4.5, zl, 6.0, zs, False)
    # площадки: +1,5 — сплошной блок, +3,0 и +4,5 — плиты
    p.box(cx, 0.75, (zn + zl) / 2.0, 3.7, 1.5, zl - zn, "concrete")
    p.slab(f"y3_{tag}_l45", [lo, zn, hi, zl], 4.5, 0.2, "concrete")
    p.slab(f"y3_{tag}_l30", [lo, zs, hi, zz], 3.0, 0.2, "concrete")
    # стена с севера (до 1,1 м над вторым этажом: она же ограждение проёма наверху)
    b.wx(zn, lo, hi, 0.0, 7.1, [], TI, "wall")
    # глухое ограждение открытой стороны: стенками вдоль маршей F1 и F3, на площадках — по 1,0 м
    xe = X(w1 + 0.06)
    _stepped(p, xe, zs, zl, 0.0)
    _stepped(p, xe, zs, zl, 3.0)
    for y in (1.5, 4.5):
        p.box(xe, y + 0.5, (zn + zl) / 2.0, 0.12, 1.0, zl - zn, "concrete")
    p.box(xe, 3.0 + 0.5, (zs + zz) / 2.0, 0.12, 1.0, zz - zs, "concrete")
    p.box(cx, 3.0 + 0.5, zz - 0.06, 3.7, 1.0, 0.12, "concrete")
    p.box(X(w1 - 0.15), 1.5, zz - 0.15, 0.3, 3.0, 0.3, "concrete")      # опора южной площадки +3,0
    # второй этаж: ограждение отверстия у колонки F3 (у F4 выход на юг)
    h0, h1 = sorted((X(xa - FW / 2.0), X(VX0)))
    p.box((h0 + h1) / 2.0, F2 + 0.55, zs, h1 - h0, 1.1, 0.12, "concrete")


def staff_stair(p, b: B) -> None:
    """ЛК-1: марши вдоль X, площадки этажей — у западного конца (дверь из тамбура), восточная — на +1,5 и +4,5."""
    ex0, ex1 = -68.8, -62.6
    wl, el = -67.2, -64.2                        # западная площадка кончается, восточная начинается
    zn0, zn1, zs0, zs1 = 84.0, 85.75, 85.95, 87.7
    cn, cs = (zn0 + zn1) / 2.0, (zs0 + zs1) / 2.0
    st = p.add["stairs"]
    def flight(xa, ya, xb, yb, z, fill):
        rec = {"from": [xa, ya, z], "to": [xb, yb, z], "width": FW, "count": 10, "mat": "concrete", "rails": "both"}
        if fill:
            rec["fill"] = 0.0
        st.append(rec)
    flight(wl, 0.0, el, 1.5, cs, True)
    flight(el, 1.5, wl, 3.0, cn, True)
    flight(wl, 3.0, el, 4.5, cs, False)
    flight(el, 4.5, wl, 6.0, cn, False)
    p.box((el + ex1) / 2.0, 0.75, (zn0 + zs1) / 2.0, ex1 - el, 1.5, zs1 - zn0, "concrete")      # восточная площадка +1,5
    p.slab("y3_sw1_l45", [el, zn0, ex1, zs1], 4.5, 0.2, "concrete")
    p.slab("y3_sw1_l30", [ex0, zn0, wl, zs1], 3.0, 0.2, "concrete")
    p.box(wl, F2 + 0.55, cs, 0.12, 1.1, zs1 - zs0, "concrete")                                    # второй этаж: край отверстия у F3


