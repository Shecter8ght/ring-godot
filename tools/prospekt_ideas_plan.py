def main() -> None:
    plt.rcParams["font.family"] = "DejaVu Sans"
    snap = json.loads(SNAPSHOT.read_text(encoding="utf-8"))
    fig = plt.figure(figsize=(16.54, 11.69), dpi=200)
    fig.text(0.012, 0.972, "Лист 9 · «Проспект»: сводный план предложений по восьми зонам и идеям", fontsize=15, weight="bold", va="top")
    fig.text(0.012, 0.944, "Серое — стоит сейчас (по снимку сцены). Цветное с номерами — предложения, в сцену не внесено. "
             "Красный пунктир — убирается. Оранжевое — под землёй.", fontsize=8.5, color="#444444", va="top")
    fig.text(0.988, 0.012, "«Проспект» · предложения, редакция 1 · 2026-11-12 · tools/prospekt_ideas_plan.py", fontsize=7,
             color="#666666", ha="right", va="bottom")
    lim = (-226.0, 200.0, -160.0, 296.0)
    ax = site_axes(fig, [0.03, 0.045, 0.60, 0.86], lim, grid=20)
    colors = {"road": "#d9d9d9", "walk": "#efece4", "parking": "#e4e4e0", "grass": "#dfe9d2", "court": "#e6d7c3", "mud": "#d8c7a8"}
    for s in snap["surfaces"]:
        r = s["rect"]
        if s["mat"] in colors:
            ax.add_patch(Rectangle((r[0], r[1]), r[2] - r[0], r[3] - r[1], fc=colors[s["mat"]], ec="none", zorder=1))
    # поворот проспекта — четверть кольца вокруг (0; 55): от западного плеча к южному
    for radius, color in ((101.95, "#efece4"), (90.15, "#d9d9d9"), (51.15, "#efece4")):
        ax.add_patch(Wedge((0.0, 55.0), radius, 270.0, 360.0, fc=color, ec="none", zorder=1.2))
    ax.add_patch(Rectangle((-152.0, 258.0), 343.3, 32.0, fc="#8f8f8f", ec="none", zorder=1.4))
    for z in (264.6, 268.7, 272.8, 276.9, 281.0, 285.1):
        ax.plot([-150.0, 187.0], [z, z], color="#555555", lw=0.4, zorder=1.5)
    b = snap["boundary"]
    ax.plot([p[0] for p in b] + [b[0][0]], [p[1] for p in b] + [b[0][1]], color="#222222", lw=1.0, ls=(0, (6, 3)), zorder=2)
    for bd in snap["buildings"]:
        if bd["region"] == "Outside":
            continue
        w, d = bd["size"]
        if abs(abs(float(bd.get("yaw", 0.0))) - 90.0) < 1.0:
            w, d = d, w
        ax.add_patch(Rectangle((bd["at"][0] - w * 0.5, bd["at"][1] - d * 0.5), w, d, fc="#bdbdbd", ec="#555555", lw=0.5, zorder=3))
    for r in ((-40.0, -2.0, -95.3, -61.3), (6.8, 17.0, -92.0, -66.0), (-146.4, -85.6, 213.8, 244.4)):     # банк, мойка, вокзал — стенами
        rect(ax, r, fc="#bdbdbd", ec="#555555", lw=0.5, zorder=3)
    for name, x, z in (("«Зерно»", -184, -54), ("банк", -21, -78), ("«Вершина»", 100, -100), ("сквер", -20, 86), ("стройка", -108, 136),
                       ("корпус 3", 144, 110), ("«Меридиан»", 151, 186), ("дом 7", -188, 51), ("«Панорама»", -120, -100)):
        ax.text(x, z, name, fontsize=5.6, color="#333333", ha="center", va="center", zorder=4)
    for r, kind, label in SHAPES:
        fc, ec = STYLE[kind]
        rect(ax, r, fc=fc, ec=ec, lw=1.2, ls=(0, (4, 3)) if kind in ("drop", "under") else "-", zorder=6, alpha=0.82 if fc != "none" else 1.0)
        if label:
            ax.text((r[0] + r[1]) * 0.5, (r[2] + r[3]) * 0.5, label, fontsize=5.4, ha="center", va="center", zorder=8, color="#111111")
    # упавшая стрела крана и трамвай
    ax.plot([-70.0, -70.0], [122.0, 86.0], color="#b5651d", lw=3.0, zorder=9)
    ax.plot([64.0, 64.0, 104.0], [60.0, 196.0, 196.0], color="#7b4ab5", lw=1.6, ls=(0, (2, 2)), zorder=9)
    ax.plot([-160.0, -160.0, -60.0], [29.0, 112.0, 112.0], color="#c0392b", lw=1.2, ls=(0, (1, 2)), zorder=9)
    for x, z, n in MARKS:
        ax.add_patch(Circle((x, z), 6.2, fc="white", ec="#b03a2e", lw=1.2, zorder=20))
        ax.text(x, z, n, fontsize=7.5, weight="bold", color="#b03a2e", ha="center", va="center", zorder=21)
    north_arrow(ax, 182.0, -122.0, 16.0)
    scale_bar(ax, -210.0, 284.0, meters=100, step=20, k=2.0)
    lines: list[str] = []
    for item in LEGEND:
        lines += textwrap.wrap(item, 62, subsequent_indent="      ") + [""]
    fig.text(0.645, 0.925, "\n".join(lines), fontsize=7.6, va="top", linespacing=1.36)
    path = OUT / "prospekt_ideas_9_master.png"
    fig.savefig(path)
    plt.close(fig)
    print("prospekt_ideas_plan:", path)


if __name__ == "__main__":
    main()
