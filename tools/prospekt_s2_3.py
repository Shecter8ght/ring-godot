def bridges_platform(p, b: B) -> None:
    for k, (x0, x1, z0, z1) in enumerate(S2.ST_BRIDGES):
        p.slab(f"st_bridge_{k}", [x0, z0, x1, z1], YC, 0.3, "steel")
        p.wall(x0 - 0.15, z0, x0, z1, YC, YC + 1.1, "steel")
        p.wall(x1, z0, x1 + 0.15, z1, YC, YC + 1.1, "steel")
    px0, px1, pz0, pz1 = PLAT
    p.wall(px0, pz0, px1, pz1, EMB_TOP, YC, "concrete")
    p.box((px0 + px1) / 2.0, YC + 0.01, pz1 - 0.2, px1 - px0, 0.02, 0.3, "stripe", 0.0, False)
    # ограждение платформы с севера (над откосом), разрывы у мостов
    cuts = [(x0 - 0.15, x1 + 0.15) for x0, x1, _, _ in S2.ST_BRIDGES]
    for a, c in spans(px0, px1, cuts):
        b.rail_x(pz0 + 0.1, a, c, YC)
    # навес и стойки, как у прежней платформы
    cw = px1 - px0
    p.box((px0 + px1) / 2.0, 11.1, 260.2, cw - 4.0, 0.2, 4.6, "slab")
    for x in range(int(px0) + 6, int(px1) - 2, 8):
        p.box(float(x), 9.3, 260.2, 0.25, 3.4, 0.25, "steel")
    for x in (110.0, 124.0, 138.0, 168.0, 176.0):
        p.put("bench", x, 261.6, 0.0, 1.0, YC)
    p.put("lamp", 106.0, 259.0, 0.0, 1.0, YC)
    p.put("lamp", 186.0, 259.0, 0.0, 1.0, YC)
    p.add["signs"].append({"at": [140.0, 10.3, 258.4], "size": 34.0, "text": "платформа 1"})
    p.add["signs"].append({"at": [184.0, 10.3, 258.4], "size": 34.0, "text": "платформа 2"})
