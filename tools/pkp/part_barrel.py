def gas_housing(h):
    """Корпус газовой трубки у ствольной коробки: коробчатая часть с защёлкой, спереди сходится к трубке."""
    F = Field("Gas_Housing", (-1, -14, -49), (114, 14, -15), h, unit=U)
    side = Poly(fillet_poly([(0.0, -47.0), (0.0, -17.0), (50.0, -17.0), (50.0, -19.3), (98.0, -19.3), (110.0, GAS_Z + GAS_R),
                             (112.0, GAS_Z + GAS_R), (112.0, GAS_Z - GAS_R), (110.0, GAS_Z - GAS_R), (98.0, -47.0)],
                            [0, 0, 0.6, 0.6, 3.0, 3.0, 0, 0, 3.0, 3.0]))
    F.add(prism(side, "XZ", -11.5, 11.5, rim=2.2))
    # переход коробчатой части в круглую трубку
    def taper(X, Y, Z):
        t = smoothstep((X - 96.0) / 14.0)
        return np.hypot(Y, Z - GAS_Z) - (20.0 - (20.0 - GAS_R) * t)
    F.apply(taper, "inter", 1.5, bbox=bb(94, 114, -14, 14, -49, -15))
    F.sub(cyl("X", (0, GAS_Z), 5.6, 60.0, 116.0), 0.3)
    # канал под шток затворной рамы и поршень: широкий у коробки, дальше — по поршню
    F.sub(cyl("X", (0, GAS_Z), 9.6 / U, -3.0, 52.0 / U, rim1=1.5), 0.0, bbox=bb(-2, 54, -11, 11, GAS_Z - 11, GAS_Z + 11))
    F.sub(cyl("X", (0, GAS_Z), 5.0 / U, 50.0 / U, 61.0), 0.0, bbox=bb(49, 62, -7, 7, GAS_Z - 7, GAS_Z + 7))
    # защёлка трубки: кольцо-рукоятка на правой и левой стороне
    for s in (-1, 1):
        ringf = cyl("Y", (42.0, -35.0), 7.0, s * 11.0, s * 13.2, rim=0.5)
        hole = cyl("Y", (42.0, -35.0), 5.2, s * 10.0, s * 15.0)
        F.add(minus(ringf, hole, 0.3), 0.3, bbox=bb(33, 51, -14, 14, -44, -26))
    # втулки под поперечные болты кронштейна-цевья (part_mounts): отверстия с буртиком на обоих бортах
    zb = FOREND_BOLT_Z / U
    for xr in FOREND_BOLT_X:
        xb = xr / U
        for s in (-1, 1):
            ya, yb = sorted((s * 11.0, s * 11.85))
            F.add(cyl("Y", (xb, zb), 3.1, ya, yb, rim=0.3), 0.25, bbox=bb(xb - 4.5, xb + 4.5, ya - 0.8, yb + 0.8, zb - 4.5, zb + 4.5))
        F.sub(cyl("Y", (xb, zb), 2.2, -14, 14), 0.25, bbox=bb(xb - 3.5, xb + 3.5, -13, 13, zb - 3.5, zb + 3.5))
    return F


def flash_hider(h):
    """Пламегаситель: цилиндр с двумя боковыми щелями, сзади контргайка-кольца."""
    R = HIDER_R
    F = Field("Flash_Hider", (HIDER_X0 - 6, -R - 1, -R - 1), (X_MUZZLE + 1, R + 1, R + 1), h, unit=U)
    # сзади — контргайка: начинается сразу за кольцом основания мушки
    prof = Poly(fillet_poly([(HIDER_X0 - 4.6, 0.0), (HIDER_X0 - 4.6, 12.9), (HIDER_X0 - 2.9, 12.9), (HIDER_X0 - 2.9, 12.2),
                             (HIDER_X0 - 1.6, 12.2), (HIDER_X0 - 1.6, 12.9), (HIDER_X0 + 1.4, 12.9), (HIDER_X0 + 2.0, R - 0.3),
                             (X_MUZZLE - 4.0, R - 0.3), (X_MUZZLE - 3.4, R), (X_MUZZLE, R), (X_MUZZLE, 0.0)],
                            [0, 0.5, 0.3, 0.2, 0.2, 0.3, 0.5, 0.3, 0.3, 0.3, 0.8, 0]))
    F.add(revolve(prof, "X", (0, 0)))
    # полость: резьба под ствол, расширительная камера, выход
    cav = Poly(fillet_poly([(HIDER_X0 - 10, 0.0), (HIDER_X0 - 10, 8.9), (HIDER_X0 + 4.0, 8.9), (HIDER_X0 + 6.0, 9.6),
                            (X_MUZZLE - 5.0, 9.6), (X_MUZZLE - 2.0, 10.4), (X_MUZZLE + 2, 10.4), (X_MUZZLE + 2, 0.0)],
                           [0, 0, 0.5, 0.6, 0.6, 0.4, 0, 0]))
    F.sub(revolve(cav, "X", (0, 0)), 0.0)
    # кромка дульного торца
    F.sub(box_e((HIDER_X0 + 14.0, -R - 3, -3.4), (HIDER_X0 + 33.0, R + 3, 3.6), ry=1.0), 0.35)
    return F


def fsb(h):
    """Основание мушки: кольцо на стволе, стойка с ограждением («ушами») и кронштейн сошек внизу."""
    F = Field("Front_Sight_Base", (FSB_X0 - 6, -15, -48), (FSB_X1 + 2, 15, 59), h, unit=U)
    ring = Poly(fillet_poly([(FSB_X0 + 1.0, 0.0), (FSB_X0 + 1.0, 13.2), (FSB_X1 - 3.4, 13.2), (FSB_X1 - 3.4, 12.6), (FSB_X1, 12.6),
                             (FSB_X1, 0.0)], [0, 0.8, 0.4, 0.3, 0.6, 0]))
    F.add(revolve(ring, "X", (0, 0)))
    # стойка мушки: задняя грань наклонная, передняя отвесная
    tower = Poly(fillet_poly([(413.0, 11.0), (430.0, 56.5), (449.5, 56.5), (449.5, 11.0)], [0, 2.0, 1.5, 0]))
    F.add(prism(tower, "XZ", -6.0, 6.0, rim=1.0), 1.5)
    # ограждение мушки: два «уха», между ними паз
    F.sub(box_e((424.0, -3.2, 45.5), (452.0, 3.2, 60.0), rx=1.0), 0.5, bbox=bb(424, 452, -5, 5, 44, 59))
    # окно в стойке и отверстие в ушах
    F.sub(box_e((428.0, -8, 24.5), (442.0, 8, 31.0), ry=1.2), 0.4, bbox=bb(426, 444, -7, 7, 23, 33))
    F.sub(cyl("Y", (441.0, 50.0), 2.6, -8, 8), 0.3, bbox=bb(437, 445, -7, 7, 46, 54))
    # кронштейн сошек: щека вниз с двумя отверстиями
    lug = Poly(fillet_poly([(421.0, -9.0), (445.0, -9.0), (443.5, -46.0), (427.0, -46.0), (421.0, -40.0)], [0, 0, 1.5, 1.5, 1.5]))
    F.add(prism(lug, "XZ", -5.0, 5.0, rim=1.0), 1.2)
    for z in (-22.5, -38.5):
        F.sub(cyl("Y", (432.5, z), 5.0, -8, 8), 0.5, bbox=bb(426, 439, -6, 6, z - 6, z + 6))
    F.sub(cyl("X", (0, 0), 10.2, FSB_X0 - 8, FSB_X1 + 4), 0.4)
    return F


HANDLE_BUMPS = (19.0, 41.0, 63.0)        # наплывы между пальцами на нижних кромках верхней полки: окно 90 мм на четыре
                                         # пальца, шаг 22 мм (у настоящего — выступы на кромках, фото B07/15 и B07/10)
FOOT_X = ((9.5, 23.5), (101.0, 115.0))   # лапки-сёдла на кожухе: за его задним кольцом и перед длинным верхним окном
FOOT_DEG = 72.0                          # лапка охватывает кожух на этот угол от верха в каждую сторону
FOOT_T = 1.8


def handle(h):
    """Ручка для переноски: рамка из гнутого профиля над кожухом и наклонная тяга к хомуту у газовой камеры.
    Нижняя полка лежит на кожухе килем (между его окнами) и держится двумя лапками-сёдлами на заклёпках, конец тяги
    приклёпан к носку кожуха. На нижних кромках верхней полки — наплывы между пальцами."""
    F = Field("Carry_Handle", (-17, -16.5, 1.5), (276, 16.5, 55), h, unit=U)
    HWd = 7.0
    outer = Poly(fillet_poly([(-15.0, 16.0), (118.0, 16.0), (118.0, 53.0), (-15.0, 53.0)], [18.0, 0.5, 2.0, 18.0], seg=16))
    F.add(prism(outer, "XZ", -HWd, HWd, rim=1.6), bbox=bb(-17, 120, -9, 9, 14, 55))
    hole = Poly(fillet_poly([(-4.0, 20.0), (86.5, 20.0), (86.5, 48.0), (-4.0, 48.0)], [2.0, 1.0, 1.0, 2.0]))
    # окно под ладонь; три наплыва на его верхней кромке остаются металлом
    bumps = union2(*[circle2((xb, 49.0), 3.8) for xb in HANDLE_BUMPS])
    F.sub(prism2(minus2(hole.sd, bumps, 1.6), "XZ", -HWd - 2, HWd + 2), 0.8, bbox=bb(-7, 89, -9, 9, 18, 50))
    # рамка — гнутый профиль: изнутри выбрана
    F.sub(box_e((-13.0, -HWd + 2.0, 17.6), (106.0, HWd - 2.0, 51.4), rx=1.0), 0.5, bbox=bb(-15, 108, -6, 6, 16.5, 52.5))
    # киль: нижняя полка опирается на кожух по всей длине (уже промежутка между диагональными окнами кожуха)
    F.add(box((9.5, -4.2, 11.0), (115.0, 4.2, 17.0), 0.0), 1.0, bbox=bb(8, 117, -6.5, 6.5, 10.5, 18.5))
    # лапки-сёдла: полосы по кожуху от киля вниз на обе стороны
    ca, sa = math.cos(math.radians(FOOT_DEG)), math.sin(math.radians(FOOT_DEG))
    for x0, x1 in FOOT_X:
        def band(X, Y, Z, x0=x0, x1=x1):
            rr = np.hypot(Y, Z)
            d = np.maximum(rr - (SHROUD_R + 0.06 + FOOT_T), (SHROUD_R - 2.0) - rr)
            d = i_round(d, np.abs(Y) * ca - Z * sa, 0.8)
            return i_round(d, np.abs(X - (x0 + x1) / 2) - (x1 - x0) / 2, 0.8)
        F.add(band, 1.0, bbox=bb(x0 - 2.5, x1 + 2.5, -16.5, 16.5, 1.5, 18.5))
    # снизу киль и лапки прилегают к кожуху по цилиндру
    F.sub(cyl("X", (0, 0), SHROUD_R + 0.06, 5.0, 120.0), 0.3, bbox=bb(7, 118, -16.5, 16.5, 1.5, 14.5))
    # заклёпки лапок: по одной на сторону
    for x0, x1 in FOOT_X:
        xm = (x0 + x1) / 2
        for s in (-1, 1):
            # поворот вокруг +X на положительный угол уводит верх в сторону −Y: знак обратный стороне
            riv = rot(cyl("Z", (xm, 0.0), 2.1, SHROUD_R + FOOT_T - 0.3, SHROUD_R + FOOT_T + 0.8, rim=0.5), "X", (0, 0, 0), -s * 54.0)
            ya, yb = sorted((s * 7.0, s * 16.5))
            F.add(riv, 0.25, bbox=bb(xm - 4.5, xm + 4.5, ya, yb, 4.0, 13.0))
    # тяга: полоса от верхней полки рамки вперёд-вниз к кожуху
    strap = Path2(fillet_path([(110.0, 51.5), (131.0, 51.5), (243.0, 20.5), (254.0, 13.1), (273.0, 13.1)], [8.0, 6.0, 6.0]))
    F.add(strip(strap, "XZ", 3.0, -6.0, 6.0, rim=0.8), 0.6, bbox=bb(105, 276, -8, 8, 10, 55))
    # конец тяги приклёпан к носку кожуха
    for x in (258.5, 267.5):
        F.add(cyl("Z", (x, 0.0), 2.3, 14.3, 15.5, rim=0.7), 0.25, bbox=bb(x - 4, x + 4, -4, 4, 13.5, 16.5))
    # винты рамки
