def barrel(h):
    """Ствол — тело вращения сеткой: казённая часть во вкладыше, рёбра под кожухом, гладкая передняя часть."""
    # казённая часть внутри коробки — тоньше гнезда вкладыша (R 11,6); буртик у торца коробки — тоньше кольца кожуха
    top = [(X_BREECH, 10.8), (X_BREECH + 0.6, 11.4), (-0.2, 11.4), (0.3, 12.2), (6.0, 12.2), (8.0, FIN_ROOT)]
    n = int((FIN_X1 - FIN_X0) / FIN_PITCH)
    for i in range(n):
        x = FIN_X0 + i * FIN_PITCH
        top += [(x, FIN_ROOT), (x + 0.22, FIN_R), (x + 0.78, FIN_R), (x + 1.0, FIN_ROOT)]
    top += [(FIN_X1 + 1.0, FIN_ROOT), (FIN_X1 + 4.0, BARREL_R_FRONT), (FSB_X0 - 1.0, BARREL_R_FRONT), (FSB_X0, 10.2),
            (HIDER_X0 - 9.0, 10.2), (HIDER_X0 - 8.0, 8.9), (HIDER_X0 + 2.4, 8.9), (HIDER_X0 + 3.0, 8.3)]
    # канал: дульная фаска, нарезная часть, пульный вход, патронник
    bore = [(HIDER_X0 + 3.0, BORE_R + 0.5), (HIDER_X0 + 2.5, BORE_R), (X_BREECH + 60.0, BORE_R), (X_BREECH + 53.7, 4.4),
            (X_BREECH + 44.3, 4.4), (X_BREECH + 39.7, 5.95), (X_BREECH + 0.6, 6.3), (X_BREECH, 6.9)]
    return lathe_mesh(top + bore, seg=96, closed=True)


def shroud(h):
    """Кожух ствола: труба из листа с продолговатыми окнами; спереди сужается и уходит под хомут газовой камеры."""
    R, T = SHROUD_R, SHROUD_T
    F = Field("Shroud", (-1, -17, -20), (SHROUD_X1 + 1, 17, 17), h, unit=U)
    prof = Poly(fillet_poly([(0.0, 0.0), (0.0, 13.6), (7.0, 13.6), (7.6, R), (232.0, R), (252.0, 11.4), (SHROUD_X1, 11.4),
                             (SHROUD_X1, 0.0)], [0, 0.6, 0.4, 0.4, 30.0, 20.0, 0, 0]))
    F.add(revolve(prof, "X", (0, 0)))
    # внутренняя полость: лист одной толщины
    inner = Poly(fillet_poly([(-2.0, 0.0), (-2.0, 12.4), (7.6, 12.4), (7.6, R - T), (232.0, R - T), (252.0, 11.4 - T),
                              (SHROUD_X1 + 2, 11.4 - T), (SHROUD_X1 + 2, 0.0)], [0, 0, 0.3, 0.3, 30.0, 20.0, 0, 0]))
    F.sub(revolve(inner, "X", (0, 0)), 0.0)
    # задние окна: четыре по диагоналям, 46 × 6 мм
    for a in (48.0, 132.0, 228.0, 312.0):
        slot = box_e((52.0, -3.0, 0.0), (98.0, 3.0, 20.0), rz=2.95)
        F.sub(rot(slot, "X", (0, 0, 0), a - 90.0), 0.35, bbox=bb(50, 100, -16, 16, -16, 16))
    # передняя половина: длинное окно сверху с двумя перемычками и окна по бокам снизу
    for x0, x1 in ((122.0, 162.0), (178.0, 217.0)):
        F.sub(box_e((x0, -4.2, 0.0), (x1, 4.2, 20.0), rz=3.0), 0.35, bbox=bb(x0 - 2, x1 + 2, -6, 6, 8, 16))
        for a in (228.0, 312.0):
            slot = box_e((x0, -2.6, 0.0), (x1, 2.6, 20.0), rz=2.55)
            F.sub(rot(slot, "X", (0, 0, 0), a - 90.0), 0.35, bbox=bb(x0 - 2, x1 + 2, -16, 16, -16, 0))
    return F


def shroud_scoop(h):
    """Нижний жёлоб кожуха (воздуховод): корыто из листа под передней половиной кожуха."""
    F = Field("Shroud_Scoop", (112, -11, -20), (226, 11, -8), h, unit=U)
    side = Poly(fillet_poly([(116.0, -11.0), (124.0, -18.3), (212.0, -18.3), (222.0, -11.0)], [0, 6.0, 6.0, 0]))
