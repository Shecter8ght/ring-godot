# ПКП: привязка боковых снимков-образцов владельца (13 — правая сторона, 14 — левая) к миллиметрам модели.
# Оба снимка — рендеры с перспективой (камера примерно в 2,25 м) и поворотом около 2° вокруг вертикали: длины спереди
# и сзади расходятся до 4 %, а кромки ближней к камере стороны сдвинуты от центра кадра (у затыльника — на 5 мм).
# Привязка: проективная вдоль оси оружия (19 парных отметок двух снимков, _asset_src/pkp/tmp/fit2.py: расхождение
# 1,3 мм) + поправка на глубину y — расстояние точки от средней плоскости в сторону камеры.
# Масштаб — по общей длине 1155 мм: крайние точки силуэта (упор приклада, срез пламегасителя) лежат ближе к камере
# на 12–15 мм, поэтому в средней плоскости миллиметров на пиксель на 0,6 % больше, чем по голому силуэту.
# Оси модели: +X к дулу, +Z вверх, −Y — правая сторона стрелка; X = 0 — передний торец ствольной коробки,
# Z = 0 — ось канала ствола.
import math

C = 1.12e-5                 # перспектива вдоль оси: 1/пикс
K = 1.00609                 # поправка масштаба на глубину крайних точек силуэта
A13 = 0.6374658 * K         # мм/пикс в средней плоскости у центра снимка 13
A14 = 0.6430654 * K         # то же у снимка 14
B14 = -2.544172 * K
D = 2250.0                  # расстояние камеры до средней плоскости, мм (оценка по длине патрона в ленте)
CX, CY = 960.0, 540.0       # главная точка — центр кадра
W = 1920
RECV_HW = 22.5              # полуширина ствольной коробки: её передний торец на снимке — кромка ближнего борта
# Подъём камеры над осью оружия, градусы (fit_cam.py по силуэту приклада и ствола): снимок 13 — строго сбоку,
# снимок 14 снят немного сверху (видны верх шейки приклада и крышка коробки с лентой). Высоты на снимке 14
# поэтому надёжны хуже (±2 мм): общее для обеих сторон берётся со снимка 13.
ELEV = {"13": 0.0, "14": 4.0}


def _f13(u):
    return u / (1.0 + C * u)


def _f14(v):
    return v / (1.0 - C * v)


# передний торец коробки на снимке 13 — пиксель 1085 (кромка борта, ближнего к камере)
_X0 = A13 * _f13((1085.0 - CX) * (D - RECV_HW) / D)
ZCAM = {"13": 52.2 * K, "14": 44.7 * K}        # высота оси канала над оптической осью камеры, мм
_SHIFT14 = B14 + (A13 * _f13(1085.0 - CX) - _X0) - A13 * _f13(1085.0 - CX)     # = B14 − _X0, запись для ясности


def to_mm(img, px, py, y=0.0):
    """Пиксель снимка → (X, Z) модели. y — на сколько точка ближе к камере, чем средняя плоскость (борт коробки —
    22,5; дальний борт — −22,5)."""
    k = (D - y) / D
    px0 = CX + (px - CX) * k; py0 = CY + (py - CY) * k
    if img == "13":
        u = px0 - CX
        return A13 * _f13(u) - _X0, (CY - py0) * A13 / (1.0 + C * u) - ZCAM["13"]
    v = (W - 1 - px0) - CX
    return A14 * _f14(v) + B14 - _X0, (CY - py0) * A14 / (1.0 - C * v) - ZCAM["14"]


def to_px(img, X, Z, y=0.0):
    """(X, Z) модели → пиксель снимка; y — как у to_mm."""
    k = D / (D - y)
    if img == "13":
        t = (X + _X0) / A13
        u = t / (1.0 - C * t)
        px0 = u + CX; py0 = CY - (Z + ZCAM["13"]) * (1.0 + C * u) / A13
    else:
        t = (X + _X0 - B14) / A14
        v = t / (1.0 + C * t)
        px0 = (W - 1) - (v + CX); py0 = CY - (Z + ZCAM["14"]) * (1.0 - C * v) / A14
    return CX + (px0 - CX) * k, CY + (py0 - CY) * k


def camera(img):
    """Камера образца для Blender: (глаз, цель, фокус в пикселях), мм модели."""
    A = A13 if img == "13" else A14
    f = D / A
    th = math.atan(C * f)                    # поворот вокруг вертикали
    x0 = -_X0 if img == "13" else (B14 - _X0)
    zc = -ZCAM[img]
    side = -1.0 if img == "13" else 1.0      # камера справа (−Y) или слева (+Y)
    # на снимке 13 дуло ближе к камере (камера смещена к дулу), на снимке 14 — дальше
    e = math.radians(ELEV[img])
    eye = (x0 - side * D * math.sin(th), side * D * math.cos(th) * math.cos(e), zc + D * math.cos(th) * math.sin(e))
    return eye, (x0, 0.0, zc), f


if __name__ == "__main__":
    for img, pts in (("13", [(62, 440, 15), (513, 460, 22.5), (1085, 457.5, 22.5), (1874, 457.5, 12.5)]),
                     ("14", [(1865, 470, 15), (831, 471, 22.5), (67, 471, 12.5)])):
        for px, py, y in pts:
            m = to_mm(img, px, py, y)
            b = to_px(img, m[0], m[1], y)
            print(img, (px, py), "y", y, "→ мм", tuple(round(v, 1) for v in m), "→ пикс", tuple(round(v, 1) for v in b))
    print("камера 13", camera("13")); print("камера 14", camera("14"))
