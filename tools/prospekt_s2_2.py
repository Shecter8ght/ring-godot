def jib_y(z: float) -> float:
    """Высота верха стрелы на широте z (прямая от JIB_A на земле до JIB_B на крыше)."""
    return ROOF * (JIB_A[1] - z) / (JIB_A[1] - JIB_B[1])


def jib_x(z: float) -> float:
    return JIB_A[0] + (JIB_B[0] - JIB_A[0]) * (JIB_A[1] - z) / (JIB_A[1] - JIB_B[1])


class B:
    """Помощники стен с проёмами на патче p (мировые оси)."""

    def __init__(self, p) -> None:
        self.p = p

    def wx(self, z, a, b, y0, h, gaps=(), t=TI, mat="wall") -> None:
        self.p.wall_x(z, a, b, y0, h, list(gaps), t, mat)

    def wz(self, x, a, b, y0, h, gaps=(), t=TI, mat="wall") -> None:
        self.p.wall_z(x, a, b, y0, h, list(gaps), t, mat)

    def rail_x(self, z: float, a: float, b: float, y: float, h: float = 1.05, mat: str = "steel") -> None:
        if b - a > 0.05:
            self.p.box((a + b) / 2.0, y + h / 2.0, z, b - a, h, 0.05, mat)

    def rail_z(self, x: float, a: float, b: float, y: float, h: float = 1.05, mat: str = "steel") -> None:
        if b - a > 0.05:
            self.p.box(x, y + h / 2.0, (a + b) / 2.0, 0.05, h, b - a, mat)


def spans(a0: float, a1: float, cuts) -> list:
    return cut(a0, a1, cuts)


