def roof(p, b: B) -> None:
    # крыша корпуса и склада; фонарь над атриумом; зенитные фонари склада (один разбит); парапет с проёмами
    p.slab("yarus_roof", [X0 - 0.15, Z0 - 0.15, X1 + 0.15, Z1 + 0.15], ROOF, 0.3, "slab", [[VOID[0], VOID[2], VOID[1], VOID[3]], [-89.5, 83.2, -87.925, 84.8]])
    p.slab("yarus_wh_roof", [WX0 - 0.15, WZ0 + 0.15, WX1 + 0.15, WZ1 + 0.15], ROOF, 0.6, "slab", [[r[0], r[2], r[1], r[3]] for r in S2.Y_SKYLIGHTS])
    # зенитные фонари: бортик; целые — со стеклянной крышкой (твёрдой), первый разбит — проём и осколки
    for k, (x0, x1, z0, z1) in enumerate(S2.Y_SKYLIGHTS):
        cx, cz = (x0 + x1) / 2.0, (z0 + z1) / 2.0
        h = 0.2 if k == 0 else 0.55
        for zz in (z0, z1):
            p.box(cx, ROOF + h / 2.0, zz, x1 - x0 + 0.3, h, 0.15, "concrete")
        for xx in (x0, x1):
            p.box(xx, ROOF + h / 2.0, cz, 0.15, h, z1 - z0, "concrete")
        if k != 0:
            p.box(cx, ROOF + h + 0.05, cz, x1 - x0 + 0.3, 0.1, z1 - z0 + 0.3, "dark")
    # разбитый фонарь: осколки на крыше, под ним — штабель ящиков, на который можно спрыгнуть (замена «стеллажа»: проём стоит между рядами)
    x0, x1, z0, z1 = S2.Y_SKYLIGHTS[0]
    p.put("glass_shards", (x0 + x1) / 2.0, z0 - 0.6, 20.0, 1.0, ROOF + 0.02)
    p.put("glass_shards", (x0 + x1) / 2.0 + 1.0, z1 + 0.6, 80.0, 1.0, ROOF + 0.02)
    cx, cz = (x0 + x1) / 2.0, (z0 + z1) / 2.0
    p.box(cx, 2.0, cz + 1.0, 2.4, 4.0, 2.4, "wood")
    p.box(cx, 1.0, cz - 1.2, 2.4, 2.0, 1.8, "wood")
    # фонарь над атриумом
