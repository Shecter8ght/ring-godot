# =============================================================================================== А3: упавшая стрела
def jib(p) -> None:
    ax, az = JIB_A
    bx, bz = JIB_B
    L = math.hypot(bx - ax, bz - az)
    ux, uz = (bx - ax) / L, (bz - az) / L
    rx, rz = -uz, ux

    def P(s: float, lat: float, y: float) -> list:
        return [round(ax + ux * s + rx * lat, 3), round(y, 3), round(az + uz * s + rz * lat, 3)]

    def Y(s: float) -> float:
        return ROOF * s / L

    mid = ((ax + bx) / 2.0, (az + bz) / 2.0)
    p.remove["pieces"].append({"list": "stairs", "rect": [mid[0] - 0.2, mid[1] - 0.2, mid[0] + 0.2, mid[1] + 0.2]})
    # настил — те же 64 ступени, но без перил
    p.add["stairs"].append({"from": [ax, 0.0, az], "to": [bx, ROOF, bz], "width": JIB_W, "count": 64, "mat": "rust"})
    lat_c = 0.85
    s_end = L - 0.6
    nodes = [2.0 * k for k in range(1, 13)] + [round(s_end, 2)]
    n0 = len(p.add["beams"])
    for sg in (-1.0, 1.0):
        lat = sg * lat_c
        p.beam(P(0.4, lat, Y(0.4) + 0.1), P(s_end, lat, Y(s_end) + 0.1), 0.25, 0.25, "hazard_yellow")             # нижний пояс
        p.beam(P(2.0, lat, Y(2.0) + 2.7), P(s_end, lat, Y(s_end) + 2.7), 0.25, 0.25, "hazard_yellow")             # верхний пояс
        for s in nodes:
            p.beam(P(s, lat, Y(s) + 0.1), P(s + 0.03, lat, Y(s) + 2.7), 0.12, 0.12, "rust")                       # стойки (чуть наклонены: look_at без вертикали)
        for i in range(len(nodes) - 1):
            a, c = nodes[i], nodes[i + 1]
            if i % 2 == 0:
                p.beam(P(a, lat, Y(a) + 0.1), P(c, lat, Y(c) + 2.7), 0.1, 0.1, "rust")                            # раскосы
            else:
                p.beam(P(a, lat, Y(a) + 2.7), P(c, lat, Y(c) + 0.1), 0.1, 0.1, "rust")
        # смятый нижний конец: верхний пояс упал на землю наружу
        p.beam(P(2.0, lat, Y(2.0) + 2.7), P(-0.9, sg * 2.5, 0.35), 0.25, 0.25, "rust")
        p.beam(P(2.0, lat, Y(2.0) + 2.7), P(0.2, sg * 1.6, 1.2), 0.08, 0.08, "rust")
    for s in nodes[1::2]:
        p.beam(P(s, -lat_c, Y(s) + 2.7), P(s, lat_c, Y(s) + 2.7), 0.12, 0.12, "rust")                             # поперечные связи
    # оторванный кусок пояса на земле и оголовок с крюковой подвеской (коробки; рядом с подъёмом, не на нём)
    p.beam(P(-2.6, -3.0, 0.2), P(2.4, -3.7, 0.25), 0.3, 0.3, "hazard_yellow")
    hx, _, hz = P(-1.6, 3.3, 0.0)
    p.box(hx, 0.7, hz, 1.1, 1.4, 0.8, "hazard_yellow", math.degrees(math.atan2(ux, uz)) % 180.0)
    p.box(hx + 0.2, 1.55, hz - 0.1, 0.8, 0.3, 0.6, "dark")
    gx, _, gz = P(-1.2, 4.7, 0.0)
    p.box(gx, 0.22, gz, 0.35, 0.44, 0.3, "dark")                                                                  # крюк
    p.beam(P(2.0, lat_c, Y(2.0) + 2.7), [hx, 1.7, hz], 0.05, 0.05, "rust")                                          # трос подвески
    p.log.append(f"А3 стрела: настил — 64 ступени без перил (уклон {math.degrees(math.atan2(ROOF, L)):.1f}°), решётка из {len(p.add['beams']) - n0} балок "
                 "(пояса 0,25, стойки, раскосы, связи), смятый нижний конец, оголовок, крюк, трос")


