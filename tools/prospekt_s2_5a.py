NFL = 5                          # маршей в башне (нечётное: верх — у дальнего торца, где проём на полотно)


def ring_towers(p) -> list:
    wx0 = -219.85
    cxa, cxb = -219.2, -217.9
    s0, s1 = 1.45, 8.25
    out = []
    for tw in R1.TOWERS:
        sgn, ez, ht = tw["sgn"], tw["entry_z"], tw["h_top"]
        z_of = lambda s: ez + sgn * s            # noqa: E731
        # убрать три прежних марша и шесть площадок (3 на башню)
        zm = z_of(4.85)
        p.remove["pieces"].append({"list": "stairs", "rect": [-219.6, zm - 0.3, -217.8, zm + 0.3]})
        for tag in ("land1", "land2", "land3"):
            p.remove["pieces"].append({"list": "slabs", "id": "ring_tower_%s_%d" % (tag, round(ez)), "rect": [-219.0, ez - 10.0, -218.0, ez + 10.0]})
        steps = max(6, int(round((ht / NFL) / STEP_RISE)))
        lamps_at = []
        for k in range(1, NFL + 1):
            xa = cxa if k % 2 == 1 else cxb
            ya, yb = ht * (k - 1) / NFL, ht * k / NFL
            sa, sb = (s0, s1) if k % 2 == 1 else (s1, s0)
            p.add["stairs"].append({"from": [xa, round(ya, 3), round(z_of(sa), 3)], "to": [xa, round(yb, 3), round(z_of(sb), 3)],
                                    "width": 1.3, "count": steps, "mat": "concrete", "rails": "both"})
            za, zb = sorted((z_of(s1), z_of(9.45))) if k % 2 == 1 else sorted((z_of(0.25), z_of(s0)))
            p.slab("ring_tower_land%d_%d" % (k, round(ez)), [wx0, za, -217.25, zb], round(yb, 3), 0.25, "concrete")
            lamps_at.append((-218.55, round(yb + 2.3, 2), round((za + zb) / 2.0, 2)))
        out.append({"ez": ez, "sgn": sgn, "ht": ht, "steps": steps, "lamps": lamps_at})
        p.log.append(f"А6 башня схода Z {ez:.1f}: {NFL} маршей по {steps} ступеней, подъём {ht / NFL:.2f} м на {s1 - s0:.2f} м "
                     f"({math.degrees(math.atan2(ht / NFL, s1 - s0)):.1f}° вместо {math.degrees(math.atan2(ht / 3.0, s1 - s0)):.1f}°)")
    return out


def ring_route() -> list:
    """Новые точки маршрута ring_deck: вверх северной башней, по полотну до юга и обратно, вниз южной."""
    A, Bc = -219.2, -217.9

    def up(ez: float, sgn: float, start_s: float) -> list:
        z = lambda s: round(ez + sgn * s, 2)       # noqa: E731
        pts = [[A, z(start_s)], [A, z(1.2)]]
        for k in range(1, NFL + 1):
            if k % 2 == 1:
                pts += [[A, z(8.2)]]
                # площадка пересекается по прямой за концами поручней (они выступают на 0,3 м за марш), а не по диагонали сквозь них
                pts += ([[A, z(8.85)]] if k == NFL else [[A, z(8.8)], [Bc, z(8.8)], [Bc, z(8.2)]])
            else:
                pts += [[Bc, z(1.45)], [Bc, z(0.8)], [A, z(0.8)], [A, z(1.4)]]
        return pts

    north = up(200.2, -1.0, -1.8)
