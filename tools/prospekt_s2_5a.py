# =============================================================================================== А1: ограждения
def fence_line(p, axis: str, c: float, a0: float, a1: float, kit: str = "bar_fence") -> int:
    """Панели вдоль отрезка: axis «x» — вдоль X на z = c, «z» — вдоль Z на x = c; шаг подгоняется под длину (панели внахлёст)."""
    n = max(1, math.ceil((a1 - a0) / PANEL - 0.02))
    step = (a1 - a0) / n
    for k in range(n):
        a = a0 + step * (k + 0.5)
        if axis == "x":
            p.put(kit, a, c, 90.0, FENCE_S)
        else:
            p.put(kit, c, a, 0.0, FENCE_S)
    return n


