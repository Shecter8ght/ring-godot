class Lights:
    def __init__(self, p) -> None:
        self.p = p

    def one(self, zone: str, x: float, y: float, z: float, e: float, r: float) -> None:
        self.p.add["lamps"].append([round(x, 2), round(y, 2), round(z, 2), e, r])
        LAMP_COUNT[zone] = LAMP_COUNT.get(zone, 0) + 1

    def room(self, zone: str, rect, y: float, e: float, r: float) -> None:
        self.one(zone, (rect[0] + rect[1]) / 2.0, y, (rect[2] + rect[3]) / 2.0, e, r)

    def grid(self, zone: str, rect, y: float, nx: int, nz: int, e: float, r: float, skip: bool = True) -> None:
        """Сетка nx × nz по прямоугольнику (x0, x1, z0, z1); каждый пятый светильник не горит (тёмные углы)."""
        i = 0
        for a in range(nx):
            for c in range(nz):
                x = rect[0] + (rect[1] - rect[0]) * (a + 0.5) / nx
                z = rect[2] + (rect[3] - rect[2]) * (c + 0.5) / nz
                i += 1
                if skip and i % 5 == 0:
                    continue
                self.one(zone, x, y, z, e, r)


