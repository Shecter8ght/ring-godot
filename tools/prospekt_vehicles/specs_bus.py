def _derive(base: dict, holes: dict | None = None, **kw) -> dict:
    """Новая машина на принятой форме: копия параметров, верхние ключи и ключи раскладки — заменой; holes —
    правка проёмов полос по имени ({имя проёма: {ключ: значение}})."""
    s = copy.deepcopy(base)
    lay = kw.pop("lay", {})
    s.update(kw)
    s["lay"].update(lay)
    for band in s["lay"]["bands"]:
        for h in band["holes"]:
            h.update((holes or {}).get(h["name"], {}))
    return s


