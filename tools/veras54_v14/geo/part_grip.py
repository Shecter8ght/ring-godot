# Контур сбоку снят с плиток образца (trace/grip: r_rear, r_front, r_neck, r_bot — сетка в мм осей ВЕРАС, глубина 0:
# передняя и задняя кромки силуэта лежат на плоскости симметрии), ширины — с плитки снизу U_x-0.20 и видов 3/4.
