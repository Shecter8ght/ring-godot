Z_TOP = PLATE_BOT - 0.15           # верх рукоятки — под накладкой скобы, зазор 0,15
R_REAR = 17.0                      # глубина скругления сечения у спинки (U_x-0.20: спинка овальная)
R_FRONT = 9.0                      # и у передней кромки (спереди сечение — прямоугольник со скруглением)
P_SEC = 2.5                        # показатель «квадратности» сечения (2 — эллипс)
CROWN = 1.0                        # выпуклость середины бока, мм: парабола поперёк оси ручки (оценка по P06, Q04)
AXIS_P0, AXIS_P1 = (36.0, -90.0), (23.3, -140.0)   # середина ручки по контуру сбоку на Z −90 и −140
AXIS_HALF = 26.0                   # полуглубина ручки поперёк оси

# контур сбоку (X, Z) по часовой стрелке от верха спинки; радиус скругления — третьим числом
PROFILE = [
    (0.4, Z_TOP + 16, 0.0),        # продолжение вверх (срезается плоскостью Z_TOP)
    (0.6, -40.0, 0.0),
    (1.5, -44.5, 1.0),             # торец «бобрового хвоста» (r_neck)
    (4.0, -46.0, 3.0),
    (8.0, -48.0, 0.0), (12.0, -50.0, 0.0), (16.0, -52.6, 0.0), (19.0, -55.5, 0.0), (21.2, -58.0, 0.0),
    (23.2, -61.0, 0.0),
    (24.4, -64.0, 3.0),            # шейка (r_neck, r_rear)
    (24.3, -67.5, 0.0), (23.1, -70.0, 0.0), (21.1, -74.0, 0.0), (17.9, -78.0, 0.0), (15.5, -82.0, 0.0),
    (13.0, -86.0, 0.0), (10.7, -90.0, 0.0), (8.4, -94.0, 0.0), (6.3, -98.0, 0.0), (4.5, -102.0, 0.0),
    (3.2, -106.0, 0.0), (2.2, -110.0, 0.0), (0.8, -116.0, 0.0), (0.0, -120.0, 0.0), (-1.1, -128.0, 0.0),
    (-1.9, -136.0, 0.0), (-2.7, -144.0, 0.0), (-3.2, -150.0, 0.0),   # спинка: +0,5 по сверке R_x-0.21 (z3a)
    (-3.7, -162.0, 0.0),           # ниже среза дна
    (51.0, -162.0, 0.0),
    (50.6, -152.0, 0.0),
    (50.3, -146.5, 1.5),           # гребень под мизинцем (r_bot)
    (48.6, -140.0, 0.0),
    (48.4, -137.5, 3.5),           # ступень 3
    (54.6, -124.5, 1.5),           # гребень
    (54.5, -110.5, 3.5),           # ступень 2 (r_front)
    (61.4, -96.5, 1.5),            # гребень
    (61.4, -86.0, 3.5),            # ступень 1
    (66.0, -79.5, 0.0),
    (70.2, -74.0, 3.0),
    (71.6, -66.0, 0.0),
    (71.6, Z_TOP + 16, 0.0),
]
# дно корпуса — плоскость через две точки (r_bot): сзади и спереди
BOT0, BOT1 = (-3.5, -149.6), (49.8, -154.2)
# крышка: верх пластины сзади и спереди (r_bot), толщина, полуширина (U_x-0.20)
CAP0, CAP1 = (-4.6, -151.2), (54.0, -157.0)
CAP_T = 2.5
CAP_HW = 17.0
# выемки-«языки» на боках, продолжение ступеней под пальцы (r_grip, l_grip, P05, P06)
# (верх спереди Z, центр закругления заднего конца X, Z, радиус, гребень спереди X, Z — конец нижней кромки)
TONGUES = [
    (-76.2, 44.0, -82.6, 5.6, 61.2, -96.2),
    (-99.6, 35.5, -105.2, 5.2, 55.0, -122.6),
    (-123.8, 25.5, -129.9, 5.6, 50.0, -146.8),
]
TONGUE_DEPTH = 0.9                 # глубина выемки (оценка по теням P05, Q03)
# пояс по верху (P14, Q01, r_neck): полимерный бортик под коробкой — чуть шире шейки, задний торец скошен,
# нижняя кромка — ступенька над шейкой; к передней колонне сужается и сходит на нет
FL_BOT = -42.0                     # низ бортика (у образца −43; верх рукоятки у нас выше на 2,4 — по накладке)
FL_HW = 16.4                       # полуширина бортика (по борту коробки)
FL_X1 = 57.0                       # где бортик сходит в переднюю колонну (передняя граница кармана)
# карман на боках верхней части (Q03, P11): рамка вокруг — несущий край у накладки, шейки и передней колонны
POCKET = [(57.0, FL_BOT - 0.6), (57.5, -60.5), (27.0, -66.0), (21.5, -59.5), (14.5, -54.0), (11.0, -50.5), (10.0, FL_BOT - 0.6)]
POCKET_R = [4.0, 5.0, 6.0, 4.0, 0.0, 4.0, 3.0]
POCKET_DEPTH = 1.4
# лунка с кнопкой (r_grip / l_grip: центр (30,5…32; −91,2), лунка Ø14, кнопка Ø10)
BTN_C = (31.0, -91.2)
LUNKA_R = 7.0
BTN_R = 5.0
LUNKA_DEPTH = 1.4
BTN_TOP = HW - 0.3                 # вершина купола кнопки по |Y| (P05: купол почти вровень с боком)
BTN_IN = HW - 6.0                  # внутренний торец кнопки
BTN_DOME = 1.3                     # высота купола
HOLE_IN = HW - 6.5                 # дно гнезда кнопки

def half_width(X):
    """Наибольшая полуширина сечения: у спинки — GRIP_HW, к передней колонне сужается."""
    return HW - (HW - HW_FRONT) * smoothstep((X - 38.0) / 34.0)


def body_fn():
    # контур сглажен: у ломаной каждый излом даёт внутрь складку вдоль биссектрисы (полосы на боку)
    prof = Poly(smooth_closed(fillet_poly([(x, z) for x, z, _ in PROFILE], [r for _, _, r in PROFILE], seg=10),
                              step=0.25, sigma=1.0))

    ax, az = AXIS_P1[0] - AXIS_P0[0], AXIS_P1[1] - AXIS_P0[1]
    ln = math.hypot(ax, az); nx, nz = ax / ln, az / ln

    def f(X, Y, Z):
        s = prof.sd(X, Z)                              # минус — внутри контура сбоку
        t = -s
        R = R_REAR + (R_FRONT - R_REAR) * smoothstep((X - 12.0) / 50.0)
        # выпуклость середины бока — гладкая парабола поперёк оси ручки (от глубины t нельзя: у t излом
        # на средней линии контура, и на боку проступала складка)
        n = ((X - AXIS_P0[0]) * nz - (Z - AXIS_P0[1]) * nx)
        W = half_width(X) - 0.6 + CROWN * np.maximum(0.0, 1.0 - (n / AXIS_HALF) ** 2)
        ay = np.abs(Y)
        u = np.maximum(R - t, 0.0) / R
        q = (u ** P_SEC + (ay / W) ** P_SEC) ** (1.0 / P_SEC)
        d_edge = W * (q - 1.0)                          # скруглённая кромка: суперэллипс в сечении
        d_mid = ay - W
        return np.where(t < R, d_edge, d_mid).astype(F32)
    return f


def side_mask(Y, W0=8.0):
    """Только бока (не середина передней и задней кромки)."""
    return smoothstep((np.abs(Y) - W0) / 4.0)


def recess(poly2, depth, soft):
    """Выемка на боках: поверхность уходит внутрь на depth внутри плоской фигуры poly2 (X, Z), край — мягкий."""
    def f(X, Y, Z):
        return -depth * smoothstep(-poly2.sd(X, Z) / soft + 0.5) * side_mask(Y)
    return f


def grip(h):
    F = Field("Pistol_Grip", (-6.0, -HW - 3.0, -156.5), (74.0, HW + 3.0, Z_TOP + 0.5), h)
    F.add(body_fn())
    # верх — плоский под накладкой, дно — плоскость под крышкой
    F.apply(half("Z", Z_TOP, 1), "inter", 0.4, bbox=bb(-6, 74, -HW - 2, HW + 2, Z_TOP - 3, Z_TOP + 0.5))
    dx, dz = BOT1[0] - BOT0[0], BOT1[1] - BOT0[1]
    F.apply(plane((BOT0[0], 0.0, BOT0[1]), (dz, 0.0, -dx)), "inter", 0.8, bbox=bb(-6, 74, -HW - 2, HW + 2, -156.5, -146))
    # пояс-бортик по верху: контур сбоку (скошенный задний торец) × план (сужение к передней колонне)
    side = Poly(fillet_poly([(0.3, Z_TOP + 4), (FL_X1, Z_TOP + 4), (FL_X1, FL_BOT), (3.6, FL_BOT), (0.3, FL_BOT + 3.4)],
                            [0, 0, 0, 1.5, 1.0], seg=8))
    plan = Poly(fillet_poly([(0.3, -FL_HW), (38.0, -FL_HW), (FL_X1 + 2.0, -11.0), (FL_X1 + 2.0, 11.0), (38.0, FL_HW),
                             (0.3, FL_HW)], [2.0, 14.0, 3.0, 3.0, 14.0, 2.0], seg=10))
    flange = inter(prism(side, "XZ", -FL_HW - 1, FL_HW + 1), prism(plan, "XY", FL_BOT - 3, Z_TOP + 4), r=1.0)
    F.add(flange, 1.2, bbox=bb(-1, FL_X1 + 2, -FL_HW - 1.5, FL_HW + 1.5, FL_BOT - 3, Z_TOP + 0.5))
    F.apply(half("Z", Z_TOP, 1), "inter", 0.4, bbox=bb(-1, FL_X1 + 2, -FL_HW - 1.5, FL_HW + 1.5, Z_TOP - 3, Z_TOP + 0.5))
    # карман на боках верхней части
    pk = Poly(fillet_poly(POCKET, POCKET_R, seg=8))
    F.displace(recess(pk, POCKET_DEPTH, 1.1), bbox=bb(3, 60, -HW - 2, HW + 2, -68, Z_TOP), fine=False)
    # выемки-продолжения ступеней под пальцы
    for zt, cx, cz, r, xr, zr in TONGUES:
        # верхняя кромка — от передней кромки назад к закруглению, полукруг заднего конца, нижняя — к гребню
        pts = [(80.0, zt), (cx + 8.0, (zt + cz + r) / 2)] + arc(cx, cz, r, 90, 270, 24) + [(xr, zr), (80.0, zr)]
        tp = Poly(smooth_closed(pts, step=0.25, sigma=0.8))
        x0 = cx - r - 3; z0 = zr - 3; z1 = zt + 3
        F.displace(recess(tp, TONGUE_DEPTH, 1.3), bbox=bb(x0, 74, -HW - 2, HW + 2, z0, z1), fine=TONGUE_DEPTH < 1.2)
    # лунки кнопок с обеих сторон: чаша с плоским дном и отверстие под кнопку
    cx, cz = BTN_C

    def lunka(X, Y, Z):
        r = np.hypot(X - cx, Z - cz)
        return -LUNKA_DEPTH * smoothstep((LUNKA_R - r) / 1.6) * side_mask(Y, 8.0)
    F.displace(lunka, bbox=bb(cx - 9, cx + 9, -HW - 3, HW + 3, cz - 9, cz + 9), fine=False)
    for s in (-1, 1):
        y0, y1 = sorted((s * HOLE_IN, s * (HW + 4)))
        F.sub(cyl("Y", (cx, cz), BTN_R + 0.2, y0, y1), 0.3, bbox=bb(cx - 7, cx + 7, y0 - 1, y1, cz - 7, cz + 7))
    # гнездо под задний конец ленты спусковой скобы (part_controls: X 70,7…72,1, лента ±6): она входит в рукоятку спереди
    F.sub(box((70.4, -6.5, -82.0), (75.0, 6.5, Z_TOP + 1.0), 0.0), 0.3, bbox=bb(69.4, 74.0, -8.0, 8.0, -83.5, Z_TOP + 0.5))
    return F


def button(side):
    """Кнопка в лунке: side = −1 — правая, +1 — левая. Цилиндр с куполом, торцом наружу."""
    cx, cz = BTN_C

    def build(h):
        y_out = side * BTN_TOP                        # вершина купола
        y_in = side * BTN_IN                          # внутренний торец (в гнезде)
        y0, y1 = sorted((y_in, y_out))
        F = Field("Grip_Button_" + ("L" if side > 0 else "R"), (cx - BTN_R - 1.5, y0 - 1.5, cz - BTN_R - 1.5),
                  (cx + BTN_R + 1.5, y1 + 1.5, cz + BTN_R + 1.5), h)
        # цилиндр, торец которого — пологий купол высотой BTN_DOME
        rs = (BTN_R ** 2 + BTN_DOME ** 2) / (2 * BTN_DOME)
        dome = sphere((cx, y_out - side * rs, cz), rs)
        F.add(inter(cyl("Y", (cx, cz), BTN_R, y0, y1, rim=0.3), dome, r=0.45))
        return F
    return build


def cap(h):
    """Крышка пенала: пластина под дном (наклон круче дна корпуса, спереди выступает — r_bot, U_x-0.20) и пробка,
    которая входит снизу под корпус (тёмная полоса между дном и пластиной на образце)."""
    (cx0, cz0), (cx1, cz1) = CAP0, CAP1
    a = math.atan2(cz1 - cz0, cx1 - cx0)               # наклон пластины (минус — вниз к носу)
    L = math.hypot(cx1 - cx0, cz1 - cz0)
    ca, sa = math.cos(a), math.sin(a)
    hw = CAP_HW
    # план — гладкий овал: сзади полукруглый, наибольшая ширина на трети длины, к носу сужается (U_x-0.20)
    pts = []
    for k in range(121):
        x = L * k / 120
        tr = min(1.0, x / 13.0)
        w = hw * math.sqrt(max(0.0, 1.0 - (1.0 - tr) ** 2))           # задний полукруг (эллипс 13 × hw)
        w *= 1.0 - 0.42 * smoothstep((x - 30.0) / (L - 30.0)) ** 1.6     # сужение к носу
        tn = min(1.0, (L - x) / 4.0)
        w *= math.sqrt(max(0.0, 1.0 - (1.0 - tn) ** 2))                  # закруглённый нос
        pts.append((x, -max(w, 0.0)))
    plan = Poly(smooth_closed(pts + [(x, -y) for x, y in reversed(pts)], step=0.25, sigma=0.6))
    boss = Poly(fillet_poly([(1.5, -9.0), (12.0, -12.6), (40.0, -11.5), (50.0, -6.0), (50.0, 6.0), (40.0, 11.5), (12.0, 12.6),
                             (1.5, 9.0)], [4, 12, 12, 4, 4, 12, 12, 4], seg=10))

    def local(X, Y, Z):
        # мир → система пластины: xl вдоль пластины от заднего торца, zl — от её верхней плоскости вверх
        x = X - cx0; z = Z - cz0
        return x * ca + z * sa, Y, -x * sa + z * ca

    def plate(X, Y, Z):
        xl, yl, zl = local(X, Y, Z)
        return prism(plan, "XY", -CAP_T, 0.0, rim=0.8, rim1=0.5)(xl, yl, zl)

    def plug(X, Y, Z):
        xl, yl, zl = local(X, Y, Z)
        return prism(boss, "XY", -1.0, 4.0, rim=0.0)(xl, yl, zl)
    dx, dz = BOT1[0] - BOT0[0], BOT1[1] - BOT0[1]
    n = math.hypot(dx, dz)
    up = (-dz / n, 0.0, dx / n)                         # нормаль дна корпуса вверх
    p_under = (BOT0[0] - up[0] * 0.15, 0.0, BOT0[1] - up[2] * 0.15)
    F = Field("Grip_Cap", (-7.0, -HW - 3.0, -161.5), (57.0, HW + 3.0, -148.0), h)
    F.add(plate)
    F.add(plug, 0.6, bbox=bb(-6, 52, -14, 14, -158, -148.5))
    F.apply(plane(p_under, up), "inter", 0.5, bbox=bb(-6, 52, -14, 14, -157, -148.5))
    return F


def parts():
    return [
        dict(name="Pistol_Grip", build=grip, h=0.13, coll="Рукоятка", mat="Polymer", adapt=0.03),
        dict(name="Grip_Cap", build=cap, h=0.1, coll="Рукоятка", mat="Polymer", adapt=0.03),
        dict(name="Grip_Button_R", build=button(-1), h=0.07, coll="Рукоятка", mat="Polymer"),
        dict(name="Grip_Button_L", build=button(1), h=0.07, coll="Рукоятка", mat="Polymer"),
    ]
