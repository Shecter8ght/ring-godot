# ВЕРАС-54 v14: пистолетная рукоятка (полимер) — объёмный корпус с выпуклыми боками, «бобровым хвостом» и шейкой,
# три ступени под пальцы спереди, переходящие на бока выемками-«языками», карман на боках верхней части, лунки
