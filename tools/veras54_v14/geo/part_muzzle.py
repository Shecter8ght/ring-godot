def ramp(X, a, b, k=0.6):
    """Плавная линейная рампа 0 → 1 на [a, b] со скруглёнными углами размера k (конус без острого ребра)."""
    def sp(u):
        return k * np.logaddexp(0.0, u / k)
    return np.clip((sp(X - a) - sp(X - b)) / (b - a), 0.0, 1.0)


def collar_section(Y, Z, bot):
    """Сечение обоймы: круг со срезами боков и верха; bot — низ (срез снизу)."""
    d = i_round(np.hypot(Y, Z) - COL_R, np.abs(Y) - COL_HW, 1.0)
    d = i_round(d, Z - COL_TOP, 1.2)
    return i_round(d, bot - Z, 0.8)


def collar(h):
    x0, x1 = COL_X0, COL_X1
    F = Field("Muzzle_Collar", (x0 - 1.0, -13.0, -21.0), (x1 + 1.0, 13.0, 16.5), h)
    # 1. тело: сечение с низом носка; длиннее торцов — торцы подрезаются в конце
    F.add(lambda X, Y, Z: np.maximum(collar_section(Y, Z, NOSE_BOT), np.abs(X - (x0 + x1) / 2) - (x1 - x0) / 2 - 1.0))
    # киль снизу (под шахту штифтов) до ступени, передняя нижняя кромка закруглена
    F.add(box_e((x0 - 1.5, -KEEL_HW, KEEL_BOT), (COL_STEP_X + 1.0, KEEL_HW, -8.0), rx=1.2, ry=2.0, rz=1.2), 1.5,
          bbox=bb(x0 - 2, COL_STEP_X + 3, -KEEL_HW - 2, KEEL_HW + 2, KEEL_BOT - 1, -6))
    # прилив-упор под задней частью
    (lx0, lx1), lhw, lbot = LUG
    F.add(box_e((lx0 - 1.5, -lhw, lbot), (lx1, lhw, KEEL_BOT + 1.0), rx=1.0, ry=1.2, rz=1.0), 2.2,
          bbox=bb(lx0 - 2, lx1 + 4, -lhw - 3, lhw + 3, lbot - 1, KEEL_BOT + 3))
    # планка-прилив сверху
    (px0, px1), phw, ptop = PLATE
    F.add(box_e((px0, -phw, COL_TOP - 1.0), (px1, phw, ptop), rx=0.6, ry=0.6, rz=0.6), 0.6,
          bbox=bb(px0 - 1, px1 + 1, -phw - 1.5, phw + 1.5, COL_TOP - 2, ptop + 1))
    # язычок фиксатора — входит в паз на кромке корпуса
    tx0, tx1, thw, ttop = TAB
    F.add(box((tx0, -thw, COL_TOP - 1.0), (tx1, thw, ttop), 0.3), 0.3, bbox=bb(tx0 - 1, tx1 + 1, -thw - 1, thw + 1, COL_TOP - 2, ttop + 1))
    # 2. торцы: задний с фаской, передний (внутри корпуса) скруглён
    F.apply(half("X", x0, -1), "inter", 0.6, bbox=bb(x0 - 1, x0 + 2, -13, 13, -21, 16.5))
    F.apply(half("X", x1, 1), "inter", 0.6, bbox=bb(x1 - 2, x1 + 1, -13, 13, -21, 16.5))
    # 3. гнездо под ствол с заходной фаской и канал пули в собственном стержне обоймы
    F.sub(cyl("X", (0, 0), SEAT_R, x0 - 2, SEAT_X1), 0.5, bbox=bb(x0 - 1, SEAT_X1 + 1, -9, 9, -9, 9))
    F.sub(cyl("X", (0, 0), BORE_R, SEAT_X1 - 1, x1 + 2), 0.3, bbox=bb(SEAT_X1 - 1, x1 + 1, -5, 5, -5, 5))
    # 4. окна насквозь по Y до ствола (дальше торца ствола — до стержня того же радиуса)
    core_r = BARREL_FRONT_R + 0.02
    for wx in WIN_X:
        win = rect2(wx - WIN_HW, wx + WIN_HW, WIN_Z[0], WIN_Z[1], WIN_R)

        def wcut(X, Y, Z, win=win):
            return np.maximum(win(X, Z), core_r - np.hypot(Y, Z))
        F.sub(wcut, 0.45, bbox=bb(wx - WIN_HW - 1, wx + WIN_HW + 1, -13, 13, WIN_Z[0] - 1, WIN_Z[1] + 1))
    # вогнутая выборка низа перед приливом (R_col: низ поднимается до −13,5 на X 563,5…569)
    F.sub(cyl("Y", (567.0 + SHIFT_X, KEEL_BOT - 4.7), 6.0, -KEEL_HW - 2, KEEL_HW + 2), 0.8,
          bbox=bb(567.0 + SHIFT_X - 6.5, 567.0 + SHIFT_X + 6.5, -KEEL_HW - 2, KEEL_HW + 2, KEEL_BOT - 5, KEEL_BOT + 3))
    # 5. отверстие прилива (под шомпол) насквозь по X
    hz, hr = LUG_HOLE
    F.sub(cyl("X", (0, hz), hr, x0 - 2, lx1 + 3), 0.35, bbox=bb(x0 - 1, lx1 + 3, -hr - 1, hr + 1, hz - hr - 1, hz + hr + 1))
    # 6. глухие отверстия под штифты (у образца пустые — тёмные)
    for px, s in PIN_HOLES:
        y0, y1 = sorted((s * 4.5, s * 12.0))
        F.sub(cyl("Y", (px, PIN_HOLE_Z), PIN_HOLE_R, y0, y1), 0.3,
              bbox=bb(px - 3, px + 3, y0 - 0.5, y1 + 0.5, PIN_HOLE_Z - 3, PIN_HOLE_Z + 3))
    return F


def rim_x(Z):
    """X косого заднего обреза корпуса на высоте Z."""
    zs = np.array([z for z, _ in RIM_ZX][::-1]); xs = np.array([x for _, x in RIM_ZX][::-1]) + SHIFT_X
    return np.interp(Z, zs, xs).astype(np.float32)


def body(h):
    x0, x1 = 584.0 + SHIFT_X, BODY_X1
    F = Field("Muzzle_Body", (x0 - 1.0, -15.5, -15.5), (x1 + 1.0, 15.5, 16.0), h)

    def outer(X, Y, Z):
        # основной цилиндр и утолщение сзади: круг, центр и радиус которого по рампе переходят в основной (конус)
        t = ramp(X, HUMP_X1, CONE_X1, 0.8)
        c = HUMP_C * (1 - t); r = HUMP_R + (BODY_R - HUMP_R) * t
        d_h = (np.hypot(Y, Z - c) - r) / 1.07
        d = np.minimum(np.hypot(Y, Z) - BODY_R, d_h)
        return np.maximum(d, np.abs(X - (x0 + x1) / 2) - (x1 - x0) / 2 - 2.0)
    F.add(outer)
    # косой задний обрез со скруглённой кромкой; передний торец скруглён
    F.apply(lambda X, Y, Z: (rim_x(Z) - X) * 0.97, "inter", 0.9, bbox=bb(x0 - 1, 628.0, -15.5, 15.5, -15.5, 16))
    F.apply(half("X", x1, 1), "inter", 1.0, bbox=bb(x1 - 2, x1 + 1, -15.5, 15.5, -15.5, 16))
    # гнездо под носок обоймы (её сечение + 0,2) до переднего конца носка + 0,3
    def socket(X, Y, Z):
        d = i_round(np.hypot(Y, Z) - (COL_R + 0.2), np.abs(Y) - (COL_HW + 0.2), 1.0)
        d = i_round(d, Z - (COL_TOP + 0.2), 1.2)
        d = i_round(d, (NOSE_BOT - 0.2) - Z, 0.8)
        return i_round(d, X - (COL_X1 + 0.3), 0.6)
    F.sub(socket, 0.4, bbox=bb(x0 - 1, COL_X1 + 1.5, -13, 13, -13, 12))
    # паз под язычок фиксатора обоймы
    tx0, tx1, thw, ttop = TAB
    # паз открыт сверху — язычок виден в нём (T_x0.345)
    F.sub(box((x0 - 2, -thw - 0.2, COL_TOP - 0.5), (tx1 + 0.3, thw + 0.2, 17.0), 0.25), 0.25,
          bbox=bb(x0 - 1, tx1 + 1.5, -thw - 1, thw + 1, COL_TOP - 1, 16.0))
    # канал пули и гнездо хвостовика наконечника (резьба внутри — не видна)
    F.sub(cyl("X", (0, 0), BORE_R, COL_X1, x1 + 2), 0.3, bbox=bb(COL_X1, x1 + 1, -5, 5, -5, 5))
    sx, sr = SPIGOT
    F.sub(cyl("X", (0, 0), sr + 0.1, sx - 0.2, x1 + 2), 0.4, bbox=bb(sx - 1, x1 + 1, -11, 11, -11, 11))
    # треугольная метка-выемка на утолщении сверху, остриём к дулу
    my = MARK_Y
    tri = Poly(fillet_poly([(MARK_X + 3.4, my), (MARK_X - 2.4, my + 3.0), (MARK_X - 2.4, my - 3.0)], 0.35))

    def mark(X, Y, Z):
        # выемка на поверхности сверху: глубина по нормали ≈ по Z (поверхность здесь пологая)
        return -0.7 * np.clip(-tri.sd(X, Y) / 0.35, 0, 1) * smoothstep((Z - 9.0) / 1.5)
    F.displace(mark, bbox=bb(MARK_X - 4, MARK_X + 5, my - 4.5, my + 4.5, 10.0, 15.5), fine=False)
    # головки штифтов: кольцевая канавка вокруг и чуть выпуклый торец заподлицо
    for px, a in BODY_PINS:
        ca, sa = math.cos(math.radians(a)), math.sin(math.radians(a))
        cy, cz = -BODY_R * sa, BODY_R * ca
        groove = rot(cyl("Z", (px, 0.0), PIN_HEAD_R + 0.35, BODY_R - 0.35, BODY_R + 1.0), "X", (0, 0, 0), a)
        F.sub(groove, 0.15, bbox=bb(px - 3, px + 3, cy - 3, cy + 3, cz - 3, cz + 3))
        head = rot(cyl("Z", (px, 0.0), PIN_HEAD_R, BODY_R - 1.5, BODY_R + 0.08, rim=0.3), "X", (0, 0, 0), a)
        F.add(head, 0.0, bbox=bb(px - 3, px + 3, cy - 3, cy + 3, cz - 3, cz + 3))
    return F


def tip(h):
    x0, x1 = TIP_X0, MUZZLE_X1
    sx, sr = SPIGOT
    F = Field("Muzzle_Tip", (sx - 1.0, -12.5, -12.5), (x1 + 1.0, 12.5, 12.5), h)
    # 1. тело вращения: кольцо и камера, переднее кольцо, ступень, конус короны
    rx0, rx1 = WIN2_X
    prof = Poly(fillet_poly([(x0, 0.0), (x0, TIP_R), (rx1 - 2.0, TIP_R), (rx1 + 0.5, RING_R + 0.15), (RING_X1, RING_R),
                             (RING_X1, CROWN_R0), (x1, CROWN_R1), (x1, 0.0)],
                            [0, 0.6, 3.0, 2.0, 0.5, 0.4, 0.35, 0]))
    F.add(revolve(prof, "X", (0, 0)))
    # хвостовик в гнезде корпуса
    F.add(cyl("X", (0, 0), sr, sx, x0 + 1.0, rim=0.4, rim1=0.0), 0.0, bbox=bb(sx - 1, x0 + 1.5, -10, 10, -10, 10))
    # 2. полость камеры и два больших боковых окна насквозь
    # полость уже окна: сквозь окно видна толстая стенка снизу и сверху (R_tip: просвет ±8,8 при окне ±10,1)
    F.sub(cyl("X", (0, 0), CAVITY_R, rx0 + 0.4, rx1 - 0.4, rim=1.2), 0.0, bbox=bb(rx0 - 1, rx1 + 1, -10.5, 10.5, -10.5, 10.5))
    win = rect2(rx0, rx1, -WIN2_Z, WIN2_Z, WIN2_R)
    # окно режет только стенки (|Y| > 3): между окнами по оси — полость, сквозь неё виден фон
    F.sub(prism2(win, "XZ", 3.0, 14.0, rim=0.0), 0.9, bbox=bb(rx0 - 1.5, rx1 + 1.5, 2.0, 12.5, -WIN2_Z - 1.5, WIN2_Z + 1.5))
    F.sub(prism2(win, "XZ", -14.0, -3.0, rim=0.0), 0.9, bbox=bb(rx0 - 1.5, rx1 + 1.5, -12.5, -2.0, -WIN2_Z - 1.5, WIN2_Z + 1.5))
    # 3. отверстие пули в стенках; на передней стенке — шероховатый поясок-цековка вокруг (F_z0.2795: кольцо до r 5,6)
    F.sub(cyl("X", (0, 0), HOLE_R, sx - 2, RING_X1 + 1.0), 0.35, bbox=bb(sx - 1, RING_X1 + 1.5, -5, 5, -5, 5))
    F.sub(cyl("X", (0, 0), 5.6, RING_X1 - 0.2, RING_X1 + 2.0), 0.3, bbox=bb(RING_X1 - 1.2, RING_X1 + 2.5, -7, 7, -7, 7))
    # 4. корона: шестигранник внутри (грани напротив зубцов), грани снаружи по зубцам, V-прорези
    ta = [math.radians(30.0 + 60.0 * k) for k in range(TEETH)]
    xc0 = RING_X1 + 0.6

    def inner(X, Y, Z):
        u = np.max(np.stack([Y * math.cos(a) + Z * math.sin(a) for a in ta]), axis=0)
        return np.maximum(u - CROWN_IN, xc0 - X)
    F.sub(inner, 0.4, bbox=bb(xc0 - 1, x1 + 1, -8, 8, -8, 8))

    def facets(X, Y, Z):
        r = CROWN_R0 + (CROWN_R1 - CROWN_R0) * np.clip((X - RING_X1) / (x1 - RING_X1), 0, 1)
        u = np.max(np.stack([Y * math.cos(a) + Z * math.sin(a) for a in ta]), axis=0)
        # позади торца кольца — не режет (иначе грани надкусывают кольцо и оставляют щепки)
        return np.minimum(u - 0.965 * r, X - RING_X1)
    F.apply(facets, "inter", 0.3, bbox=bb(RING_X1 + 0.3, x1 + 1, -12, 12, -12, 12))
    tan_a = SLOT_HW_TIP / (x1 - SLOT_APEX_X)
    cos_a = 1.0 / math.hypot(1.0, tan_a)
    for k in range(TEETH):
        p = math.radians(60.0 * k)
        cp, spn = math.cos(p), math.sin(p)

        def slot(X, Y, Z, cp=cp, spn=spn):
            t = -Y * spn + Z * cp
            u = Y * cp + Z * spn
            # дно прорези — узкое скругление шириной 0,7, а не нож: иначе у вершины остаются щепки
            d_v = (np.abs(t) - 0.35 - np.maximum(X - SLOT_APEX_X, 0.0) * tan_a) * cos_a
            return np.maximum(np.maximum(d_v, SLOT_APEX_X - X), 3.0 - u)
        F.sub(slot, 0.35, bbox=bb(SLOT_APEX_X - 1.5, x1 + 1, -12, 12, -12, 12))
    return F


