def base(ax, snap: dict, lim: tuple, skip: tuple = ()) -> None:
    """Покрытия, поворот, насыпь и постройки из снимка сцены (серое)."""
    colors = {"road": "#d9d9d9", "walk": "#efece4", "parking": "#e4e4e0", "grass": "#dfe9d2", "court": "#e6d7c3", "mud": "#dccdb2"}
    for s in snap["surfaces"]:
        r = s["rect"]
        if s["mat"] in colors and s["id"] not in skip and not (r[2] < lim[0] or r[0] > lim[1] or r[3] < lim[2] or r[1] > lim[3]):
            ax.add_patch(Rectangle((r[0], r[1]), r[2] - r[0], r[3] - r[1], fc=colors[s["mat"]], ec="none", zorder=1))
    for radius, color in ((101.95, "#efece4"), (90.15, "#d9d9d9"), (51.15, "#efece4")):
        ax.add_patch(Wedge((0.0, 55.0), radius, 270.0, 360.0, fc=color, ec="none", zorder=1.2))
    ax.add_patch(Rectangle((-218.0, 258.0), 409.3, 32.0, fc="#8f8f8f", ec="none", zorder=1.4))
    ax.add_patch(Rectangle((-218.0, 244.0), 409.3, 14.0, fc="#b9c2ae", ec="none", zorder=1.3))
    for z in (264.6, 268.7, 272.8, 276.9, 281.0, 285.1):
        ax.plot([-218.0, 190.0], [z, z], color="#555555", lw=0.4, zorder=1.5)
    for bd in snap["buildings"]:
        if bd["id"] in skip or bd["id"] in REMOVE_OUTSIDE:
            continue
        w, d = bd["size"]
        if abs(abs(float(bd.get("yaw", 0.0))) - 90.0) < 1.0:
            w, d = d, w
        outside = bd["region"] == "Outside"
        ax.add_patch(Rectangle((bd["at"][0] - w * 0.5, bd["at"][1] - d * 0.5), w, d, fc="#e6e6e6" if outside else "#bdbdbd",
                               ec="#999999" if outside else "#555555", lw=0.5, zorder=3))
    for r in ((-40.0, -2.0, -95.3, -61.3), (6.8, 17.0, -92.0, -66.0)):
        rect(ax, r, fc="#bdbdbd", ec="#555555", lw=0.5, zorder=3)


