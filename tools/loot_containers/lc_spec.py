def main() -> None:
    pieces = json.loads(PIECES.read_text(encoding="utf-8"))
    slots, problems = [], []
    for game, rows in TABLE.items():
        seen = {}
        for sid, title, finish, parts, ov, note in rows:
            for p in parts:
                if p in seen:
                    problems.append(f"{game}: {p} в двух слотах ({seen[p]}, {sid})")
                seen[p] = sid
            slots.append({"id": f"{game[3:]}_{sid}", "title": title, "items": [game], "parts": parts, "finish": finish,
                          "overrides": ov, "note": ("Выбор по слотам сделан исполнителем по ответам интервью. " + note).strip()})
        for p in pieces.get(game, []):
            if p not in seen:
                problems.append(f"{game}: нет слота у {p}")
        for p in seen:
            if p not in pieces.get(game, []):
                problems.append(f"{game}: в слоте есть {p}, в развёртке нет")
    if problems:
        raise SystemExit("\n".join(problems))
    spec = {"schema": "ring-finish-spec/1", "asset": "RING_Loot_Containers — партия 1",
            "model": str(LIB / "models" / "RING_Loot_Containers_uv_v01.blend"), "stage": "factory", "slots": slots,
            "interview": INTERVIEW, "favorites": [], "requests": [], "history": [], "accepted": False}
    (LIB / "finish-spec.json").write_text(json.dumps(spec, ensure_ascii=False, indent=1) + "\n", encoding="utf-8", newline="\n")
    print("слотов:", len(slots))


if __name__ == "__main__":
    main()
