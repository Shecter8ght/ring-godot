def slot_starts(x0, x1):
    """Пазы планки по середине отрезка: на концах — целые зубья."""
    tooth = PITCH - SLOT_W
    n = int((x1 - x0 - tooth) // PITCH)
    span = n * PITCH + tooth
    start = x0 + (x1 - x0 - span) / 2 + tooth
    return [start + i * PITCH for i in range(n)]
